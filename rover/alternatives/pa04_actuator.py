"""PA-04 900 lbf, 12 V chart approximation. See docs/PA04_ACTUATORS.md.

Pure helpers reject extrapolation. Components retain explicitly flagged finite
diagnostics outside the domain so an optimizer can recover from invalid trials.
No measured lowering curve or independent hardware validation is available.
"""
import math
import hashlib
import json
from pathlib import Path
from ..components import scalar
from ..discipline import Discipline, names
from ..linkage import LinkageGeometry
from .offset_attachment import physical_length
from ..dependencies import dependencies

INCH = .0254
LB = .45359237
RATED_FORCE = 900 * 4.4482216152605
VOLTAGE = 12.
MIN_STROKE, MAX_STROKE = 2*INCH, 40*INCH
# Generated by data/actuators/fit_pa04.py; global affine least-squares fit.
MASS_INTERCEPT_LB = 4.376918958521191
MASS_SLOPE_LB_PER_IN = .1574588593327322


def verify_source_data():
    """Verify versioned transcriptions once during explicit problem construction."""
    root = Path(__file__).resolve().parents[2]/"data/actuators"
    manifest = json.loads((root/"manifest.json").read_text(encoding="utf-8"))
    for name, expected in manifest["sha256"].items():
        if hashlib.sha256((root/name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"PA-04 source hash mismatch: {name}; update manifest/fit deliberately")
    if (manifest["mass_fit"]["intercept_lb"], manifest["mass_fit"]["slope_lb_per_in"]) != (MASS_INTERCEPT_LB, MASS_SLOPE_LB_PER_IN):
        raise ValueError("PA-04 mass coefficients do not match their manifest")


def catalog_geometry(stroke, allowance=.1613408):
    """Installed lengths [m] and per-actuator catalog mass [kg]."""
    if not math.isfinite(stroke) or not MIN_STROKE <= stroke <= MAX_STROKE:
        raise ValueError("PA-04 mass/length model supports strokes from 2 to 40 inches")
    if not math.isfinite(allowance) or allowance < 0:
        raise ValueError("Installation allowance must be finite and nonnegative")
    return _catalog_diagnostics(stroke, allowance)


def _catalog_diagnostics(stroke, allowance):
    retracted = stroke + 7.87*INCH + allowance
    return retracted, retracted + stroke, (MASS_INTERCEPT_LB + MASS_SLOPE_LB_PER_IN*stroke/INCH)*LB


def load_performance(force):
    """Opposing axial load magnitude [N] -> speed [m/s], current [A]."""
    if not math.isfinite(force) or not 0 <= force <= RATED_FORCE:
        raise ValueError("PA-04 900 lbf load curve supports 0 through 900 lbf only")
    fraction = force/RATED_FORCE
    return (.47 - .08*fraction)*INCH, 4. + 10.*fraction


def cycle_performance(force, stroke, lowering_time):
    """Two parallel actuators; constant raising envelope and rated-load lowering.

    Chart electrical power already includes the motor losses/no-load current.
    Do not add the reference idle power or apply actuator_efficiency again.
    """
    speed, current = load_performance(force)
    if not all(math.isfinite(x) and x >= 0 for x in (stroke, lowering_time)):
        raise ValueError("Motion distance and lowering time must be nonnegative")
    raising_time = stroke/speed
    return {"actuator_loaded_speed": speed, "actuator_raising_current": current,
            "actuator_lowering_current": 14., "actuator_raising_time": raising_time,
            "actuation_time": raising_time+lowering_time,
            "arm_energy": 2*VOLTAGE*(current*raising_time+14.*lowering_time),
            "arm_peak_power": 2*VOLTAGE*max(current, 14.)}


class PA04LinkageGeometry(LinkageGeometry):
    OUTPUT_UNITS = {**LinkageGeometry.OUTPUT_UNITS,
                    "actuator_catalog_retracted_length": "m",
                    "actuator_catalog_extended_length": "m",
                    "actuator_unit_mass": "kg", "actuator_stroke_domain_margin": "m"}
    DEPENDENCIES = {**dependencies("LinkageGeometry"),
        "actuator_catalog_retracted_length": names("actuator_catalog_stroke actuator_installation_allowance"),
        "actuator_catalog_extended_length": names("actuator_catalog_stroke actuator_installation_allowance"),
        "actuator_unit_mass": {"actuator_catalog_stroke"},
        "actuator_stroke_domain_margin": {"actuator_catalog_stroke"},
        "linkage_mass": names("actuator_catalog_stroke arm_linear_mass arm_length lin_act_side_arm_offset"),
        "actuator_body_margin": names("actuator_catalog_stroke actuator_installation_allowance travel_actuator_length deposition_actuator_length actuator_retracted_length actuator_extended_length")}

    def setup(self):
        # Reference geometry, clearances and force leverage remain shared.
        super().setup()
        self.inputs_from_config("actuator_catalog_stroke", "actuator_installation_allowance")
        self.model_evidence = {"status": "manufacturer charts transcribed by student; no hardware validation",
                               "manifest": "data/actuators/manifest.json"}

    def compute(self, inputs, outputs):
        super().compute(inputs, outputs)
        v = lambda n: scalar(inputs, n)
        stroke = v("actuator_catalog_stroke")
        lo, hi, mass = _catalog_diagnostics(stroke, v("actuator_installation_allowance"))
        outputs["actuator_catalog_retracted_length"] = lo
        outputs["actuator_catalog_extended_length"] = hi
        outputs["actuator_unit_mass"] = mass
        outputs["actuator_stroke_domain_margin"] = min(stroke-MIN_STROKE, MAX_STROKE-stroke)
        outputs["linkage_mass"] = 2*(mass+v("arm_linear_mass")*physical_length(v("arm_length"),v("lin_act_side_arm_offset")))
        # Installed catalog interval reserve, retained as a diagnostic only.
        outputs["actuator_body_margin"] = min(
            min(v(n)-lo, hi-v(n)) for n in
            ("travel_actuator_length", "deposition_actuator_length", "actuator_retracted_length", "actuator_extended_length"))


class PA04LinkageLoads(Discipline):
    model_evidence = {"status": "chart approximation with conservative phase load envelopes; unvalidated hardware",
                      "manifest": "data/actuators/manifest.json"}
    CONFIG_INPUTS = tuple(names("gravity actuator_safety_factor breakout_force arm_length lin_act_side_arm_offset"))
    COUPLED_INPUTS = {"drum_mass": "kg", "payload_mass": "kg", "arm_linear_mass": "kg/m",
                      "actuator_leverage_max": None, "stroke": "m", "lowering_time": "s"}
    OUTPUT_UNITS = {"required_actuator_force": "N", "actuator_force_margin": "N",
                    "actuator_curve_margin": "N", "actuator_curve_valid": None,
                    "actuator_loaded_speed": "m/s", "actuator_raising_current": "A",
                    "actuator_lowering_current": "A", "actuator_raising_time": "s",
                    "actuation_time": "s", "arm_energy": "J", "arm_peak_power": "W"}
    force_inputs = names("drum_mass payload_mass arm_linear_mass arm_length lin_act_side_arm_offset gravity breakout_force actuator_leverage_max")
    DEPENDENCIES = {
        "required_actuator_force": force_inputs,
        "actuator_force_margin": force_inputs | {"actuator_safety_factor"},
        "actuator_curve_margin": force_inputs,
        "actuator_curve_valid": force_inputs,
        "actuator_loaded_speed": force_inputs, "actuator_raising_current": force_inputs,
        "actuator_lowering_current": set(),
        "actuator_raising_time": force_inputs | {"stroke"},
        "actuation_time": force_inputs | names("stroke lowering_time"),
        "arm_energy": force_inputs | names("stroke lowering_time"),
        "arm_peak_power": force_inputs,
    }

    def compute(self, inputs, outputs):
        v = lambda n: scalar(inputs, n)
        weight = (v("drum_mass")/2 + v("payload_mass")/2
                  + v("arm_linear_mass")*physical_length(v("arm_length"),v("lin_act_side_arm_offset"))**2/(2*v("arm_length")))*v("gravity")
        force = (weight+v("breakout_force"))*v("actuator_leverage_max")
        outputs["required_actuator_force"] = force
        outputs["actuator_force_margin"] = RATED_FORCE/v("actuator_safety_factor")-force
        outputs["actuator_curve_margin"] = min(force, RATED_FORCE-force)
        outputs["actuator_curve_valid"] = float(0 <= force <= RATED_FORCE)
        # Guarded diagnostic only: the original load keeps its failing margins.
        result = cycle_performance(min(max(force, 0.), RATED_FORCE), max(v("stroke"), 0.), v("lowering_time"))
        for name, value in result.items():
            outputs[name] = value


